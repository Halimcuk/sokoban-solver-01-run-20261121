// Sokoban solver for make.fun's sokoban-solver-01-run-20261121.
// Written from scratch for this bounty (MIT).
//
// Strategy
// --------
// The generator's levels are a 1-wide hallway with 1-4 rooms off it, each
// room holding 3-4 boxes and as many goals, and a box pushed out of its room
// can never come back -- so every room is solved independently and the
// level's push-optimum is the sum of its rooms' optima. We exploit that:
//
//  1. Split the level into rooms: cut the hallway row's dead squares (a box
//     there can reach no goal) out of the floor and flood-fill the rest.
//     Each connected part holding boxes is one room.
//  2. Solve each room push-optimally with A* over push states (a state is
//     the boxes' squares plus the player's reachable region, named by its
//     lowest square). The heuristic is the minimum-assignment cost of the
//     boxes to the goals under shortest-path distances on the open floor
//     (ignoring other boxes), which is admissible -- one push moves one box
//     one square -- and consistent, so the first goal state popped is
//     push-optimal.
//  3. Prune dead states: a box on a dead square (no pull path from any goal
//     reaches it) and a box frozen in a 2x2 block of walls/boxes with a box
//     off its goal can never be solved, so those pushes are never made.
//  4. If the level does not split into rooms, fall back to the same A* over
//     the whole level (with a weaker sum-of-minima heuristic, since a full
//     assignment is too big for many boxes).
//
// Determinism: no clock, no randomness, no environment reads. Search is
// bounded by a fixed number of generated states per room, never by time,
// so two runs write the same bytes. Direction order is fixed (u, d, l, r)
// everywhere, and heap ties break by insertion order.
//
// If a room's search exhausts its state budget the level is left
// unanswered (empty solution) rather than risking an illegal or
// over-long answer.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const I = process.env.MAKEFUN_INPUT_DIR ?? '/input';
const O = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';

/** Max states generated by one room search (work budget, never the clock). */
const MAX_STATES = 400_000;
/** Max states generated by the whole-level fallback search. */
const MAX_STATES_WHOLE = 400_000;

/** [dx, dy, step letter, push letter], fixed order everywhere. */
const DIRS = [
  [0, -1, 'u', 'U'],
  [0, 1, 'd', 'D'],
  [-1, 0, 'l', 'L'],
  [1, 0, 'r', 'R'],
];

/** Parse XSB text into a level object. */
function parseLevel(text) {
  const rows = text.split('\n').filter((r) => r.length > 0);
  const h = rows.length;
  const w = Math.max(...rows.map((r) => r.length));
  const wall = new Uint8Array(w * h).fill(1);
  const goals = [];
  const boxes = [];
  let player = -1;
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      const i = y * w + x;
      if (ch === '#') continue;
      wall[i] = 0;
      if (ch === '.' || ch === '*' || ch === '+') goals.push(i);
      if (ch === '$' || ch === '*') boxes.push(i);
      if (ch === '@' || ch === '+') player = i;
    }
  });
  // The outer frame is wall whatever it shows.
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (x === 0 || y === 0 || x === w - 1 || y === h - 1) wall[y * w + x] = 1;
    }
  }
  return { w, h, wall, goals, boxes: boxes.sort((a, b) => a - b), player };
}

/**
 * Live squares: from which a box, pulled backwards from a goal over open
 * floor (ignoring other boxes), can reach some goal. A box off a live
 * square is dead and the level is unsolvable from there.
 */
function liveSquares(level) {
  const { w, wall, goals } = level;
  const live = new Uint8Array(wall.length);
  const queue = [];
  for (const g of goals) {
    live[g] = 1;
    queue.push(g);
  }
  for (let qi = 0; qi < queue.length; qi++) {
    const x = queue[qi];
    for (const [dx, dy] of DIRS) {
      const d = dy * w + dx;
      const y = x - d; // the square the box is pulled from
      if (!wall[y] && !wall[y - d] && !live[y]) {
        live[y] = 1;
        queue.push(y);
      }
    }
  }
  return live;
}

/** Shortest-path distances on open floor from every square to each goal. */
function goalDistances(level) {
  const { w, wall, goals } = level;
  const dists = goals.map(() => {
    const d = new Int32Array(wall.length).fill(-1);
    return d;
  });
  goals.forEach((g, gi) => {
    const d = dists[gi];
    const queue = [g];
    d[g] = 0;
    for (let qi = 0; qi < queue.length; qi++) {
      const p = queue[qi];
      for (const [dx, dy] of DIRS) {
        const q = p + dy * w + dx;
        if (!wall[q] && d[q] === -1) {
          d[q] = d[p] + 1;
          queue.push(q);
        }
      }
    }
  });
  return dists;
}

/** All permutations of [0..n) as index arrays (n <= 4 here). */
function permutations(n) {
  const out = [];
  const cur = [];
  const used = new Array(n).fill(false);
  (function gen() {
    if (cur.length === n) {
      out.push(cur.slice());
      return;
    }
    for (let i = 0; i < n; i++) {
      if (used[i]) continue;
      used[i] = true;
      cur.push(i);
      gen();
      cur.pop();
      used[i] = false;
    }
  })();
  return out;
}

/**
 * Minimum-assignment heuristic: the cheapest way to match each box to a
 * distinct goal under the floor distances. Admissible and consistent.
 * Returns Infinity when some box cannot reach any goal.
 */
function assignmentHeuristic(boxes, goals, dists, perms) {
  let best = Infinity;
  for (const p of perms) {
    let sum = 0;
    for (let i = 0; i < boxes.length; i++) {
      const d = dists[p[i]][boxes[i]];
      if (d < 0) {
        sum = Infinity;
        break;
      }
      sum += d;
    }
    if (sum < best) best = sum;
  }
  return best;
}

/** Sum of each box's distance to its nearest goal (admissible, weaker). */
function sumMinHeuristic(boxes, dists) {
  let sum = 0;
  for (const b of boxes) {
    let m = Infinity;
    for (const d of dists) if (d[b] >= 0 && d[b] < m) m = d[b];
    if (m === Infinity) return Infinity;
    sum += m;
  }
  return sum;
}

/**
 * Flood-fill the player's reachable region from `from` with `occupied` in
 * the way, marking `seen` with `stamp`; returns the region's lowest square.
 */
function reach(level, occupied, from, seen, stamp, stack) {
  const { w, wall } = level;
  let low = from;
  let n = 0;
  stack[n++] = from;
  seen[from] = stamp;
  while (n > 0) {
    const p = stack[--n];
    if (p < low) low = p;
    for (let k = 0; k < 4; k++) {
      const q = k === 0 ? p - w : k === 1 ? p + w : k === 2 ? p - 1 : p + 1;
      if (wall[q] === 0 && occupied[q] === 0 && seen[q] !== stamp) {
        seen[q] = stamp;
        stack[n++] = q;
      }
    }
  }
  return low;
}

/** Whether the box just pushed to `t` sits frozen in a 2x2 wall/box block. */
function frozenBlock(level, occupied, goal, t) {
  const { w, wall } = level;
  for (const a of [t, t - 1, t - w, t - w - 1]) {
    const b = a + 1;
    const c = a + w;
    const d = c + 1;
    if (!(wall[a] || occupied[a]) || !(wall[b] || occupied[b]) || !(wall[c] || occupied[c]) || !(wall[d] || occupied[d])) continue;
    if ((occupied[a] && !goal[a]) || (occupied[b] && !goal[b]) || (occupied[c] && !goal[c]) || (occupied[d] && !goal[d])) return true;
  }
  return false;
}

/** The shortest walk from `from` to `to` around walls and boxes (lowercase). */
function walkTo(level, occupied, from, to) {
  const { w, wall } = level;
  if (from === to) return '';
  const prev = new Int32Array(wall.length).fill(-1);
  const how = new Array(wall.length);
  const queue = [from];
  prev[from] = from;
  for (let qi = 0; qi < queue.length; qi++) {
    const p = queue[qi];
    if (p === to) break;
    for (const [dx, dy, letter] of DIRS) {
      const q = p + dy * w + dx;
      if (wall[q] || occupied[q] || prev[q] !== -1) continue;
      prev[q] = p;
      how[q] = letter;
      queue.push(q);
    }
  }
  if (prev[to] === -1) throw new Error('walkTo: push square out of reach');
  let s = '';
  for (let p = to; p !== from; p = prev[p]) s = how[p] + s;
  return s;
}

/** The square the player stands on after `moves` from `from` on a board `w` wide. */
function endOf(w, from, moves) {
  let p = from;
  for (const ch of moves.toLowerCase()) p += ch === 'u' ? -w : ch === 'd' ? w : ch === 'l' ? -1 : 1;
  return p;
}

/**
 * Push-optimal A* for one level (a room sub-level or a whole level).
 * Returns {pushes, moves} or null when the state budget runs out or the
 * level is unsolvable. `exact` picks the min-assignment heuristic (small
 * box counts) over the sum-of-minima one.
 */
function solvePushOptimal(level, maxStates, exact) {
  const { w, wall, goals } = level;
  const size = wall.length;
  const goal = new Uint8Array(size);
  for (const g of goals) goal[g] = 1;
  const live = liveSquares(level);
  if (level.boxes.some((b) => !live[b])) return null;
  const dists = goalDistances(level);
  const perms = exact ? permutations(goals.length) : null;
  const heuristic = (boxes) =>
    exact ? assignmentHeuristic(boxes, goals, dists, perms) : sumMinHeuristic(boxes, dists);
  const solved = (boxes) => boxes.every((b) => goal[b]);

  const occupied = new Uint8Array(size);
  const seen = new Int32Array(size);
  const mark = new Int32Array(size);
  const stack = new Int32Array(size);
  let stamp = 0;

  // Numeric state key: region-low * size^(n+1) + boxes; exact while
  // size ** (boxes + 1) < 2 ** 53. Rooms hold <= 4 boxes, so this holds;
  // the whole-level fallback uses a string key instead.
  const numericKey = exact && size ** (level.boxes.length + 1) < 2 ** 53;
  const keyOf = numericKey
    ? (boxes, low) => {
        let k = low;
        for (const b of boxes) k = k * size + b;
        return k;
      }
    : (boxes, low) => `${low}:${boxes.join(',')}`;

  // State storage: boxes, player square, parent, the push that made it.
  const stBoxes = [level.boxes];
  const stPlayer = [level.player];
  const stParent = [-1];
  const stPushFrom = [-1]; // box square before the push
  const stPushDir = [-1]; // index into DIRS
  const stG = [0];

  const h0 = heuristic(level.boxes);
  if (h0 === Infinity) return null;
  if (solved(level.boxes)) return { pushes: 0, moves: '' };

  const best = new Map();
  for (const b of level.boxes) occupied[b] = 1;
  const low0 = reach(level, occupied, level.player, seen, ++stamp, stack);
  for (const b of level.boxes) occupied[b] = 0;
  best.set(keyOf(level.boxes, low0), 0);

  // Binary heap on [f, g, insertion counter, state index].
  const heap = [];
  let counter = 0;
  const less = (a, b) => a[0] < b[0] || (a[0] === b[0] && (a[1] < b[1] || (a[1] === b[1] && a[2] < b[2])));
  const heapPush = (e) => {
    let i = heap.length;
    heap.push(e);
    while (i > 0) {
      const p = (i - 1) >> 1;
      if (!less(heap[i], heap[p])) break;
      const tmp = heap[i];
      heap[i] = heap[p];
      heap[p] = tmp;
      i = p;
    }
  };
  const heapPop = () => {
    const top = heap[0];
    const last = heap.pop();
    if (heap.length > 0) {
      heap[0] = last;
      for (let i = 0; ; ) {
        let c = 2 * i + 1;
        if (c >= heap.length) break;
        if (c + 1 < heap.length && less(heap[c + 1], heap[c])) c++;
        if (!less(heap[c], heap[i])) break;
        const tmp = heap[i];
        heap[i] = heap[c];
        heap[c] = tmp;
        i = c;
      }
    }
    return top;
  };
  heapPush([h0, 0, counter++, 0]);

  let found = -1;
  while (heap.length > 0) {
    const [, g, , s] = heapPop();
    if (g !== stG[s]) continue; // superseded entry
    const boxes = stBoxes[s];
    if (solved(boxes)) {
      found = s;
      break;
    }
    for (const b of boxes) occupied[b] = 1;
    reach(level, occupied, stPlayer[s], seen, ++stamp, stack);
    const here = stamp;
    for (let bi = 0; bi < boxes.length; bi++) {
      const b = boxes[bi];
      for (let di = 0; di < 4; di++) {
        const [dx, dy] = DIRS[di];
        const d = dy * w + dx;
        const t = b + d;
        if (seen[b - d] !== here || wall[t] || occupied[t] || !live[t]) continue;
        occupied[b] = 0;
        occupied[t] = 1;
        if (frozenBlock(level, occupied, goal, t)) {
          occupied[t] = 0;
          occupied[b] = 1;
          continue;
        }
        const next = boxes.slice();
        next[bi] = t;
        next.sort((x, y) => x - y);
        const low = reach(level, occupied, b, mark, ++stamp, stack);
        occupied[t] = 0;
        occupied[b] = 1;
        const key = keyOf(next, low);
        const prevG = best.get(key);
        if (prevG !== undefined && prevG <= g + 1) continue;
        if (stBoxes.length >= maxStates) return null;
        const h = heuristic(next);
        if (h === Infinity) continue;
        best.set(key, g + 1);
        stBoxes.push(next);
        stPlayer.push(b);
        stParent.push(s);
        stPushFrom.push(b);
        stPushDir.push(di);
        stG.push(g + 1);
        heapPush([g + 1 + h, g + 1, counter++, stBoxes.length - 1]);
      }
    }
    for (const x of boxes) occupied[x] = 0;
  }
  if (found < 0) return null;

  // Reconstruct: walk to each push square, then push.
  const path = [];
  for (let s = found; s > 0; s = stParent[s]) path.push(s);
  path.reverse();
  let moves = '';
  let player = level.player;
  let boxes = level.boxes;
  for (const s of path) {
    const nextBoxes = stBoxes[s];
    const from = stPushFrom[s];
    const di = stPushDir[s];
    const [dx, dy, , pushLetter] = DIRS[di];
    const d = dy * w + dx;
    for (const b of boxes) occupied[b] = 1;
    moves += walkTo(level, occupied, player, from - d);
    for (const b of boxes) occupied[b] = 0;
    moves += pushLetter;
    player = from;
    boxes = nextBoxes;
  }
  return { pushes: path.length, moves };
}

/**
 * Split a level into rooms: cut the dead squares of the player's (hallway)
 * row out of the floor; each remaining part holding boxes is a room.
 * Returns null when the level is no set of rooms.
 */
function roomsOf(level) {
  const { w, wall, goals, boxes, player } = level;
  const live = liveSquares(level);
  const row = Math.floor(player / w);
  const cut = new Uint8Array(wall.length);
  for (let i = row * w; i < (row + 1) * w; i++) {
    if (!wall[i] && !live[i]) cut[i] = 1;
  }
  if (boxes.some((b) => cut[b])) return null;
  const part = new Int32Array(wall.length).fill(-1);
  const rooms = [];
  for (let s = 0; s < wall.length; s++) {
    if (wall[s] || cut[s] || part[s] >= 0) continue;
    const squares = [s];
    part[s] = rooms.length;
    for (let i = 0; i < squares.length; i++) {
      for (const [dx, dy] of DIRS) {
        const q = squares[i] + dy * w + dx;
        if (!wall[q] && !cut[q] && part[q] < 0) {
          part[q] = rooms.length;
          squares.push(q);
        }
      }
    }
    rooms.push({ squares, boxes: [], goals: [], done: false });
  }
  for (const b of boxes) {
    if (part[b] < 0) return null;
    rooms[part[b]].boxes.push(b);
  }
  for (const g of goals) {
    if (part[g] < 0) return null;
    rooms[part[g]].goals.push(g);
  }
  if (rooms.some((r) => r.boxes.length !== r.goals.length)) return null;
  return rooms.filter((r) => r.boxes.length > 0);
}

/** Solve a level room by room; null when any room fails or it is no set of rooms. */
function solveByRooms(level) {
  const rooms = roomsOf(level);
  if (rooms === null) return null;
  let player = level.player;
  let pushes = 0;
  let moves = '';
  for (const room of rooms) {
    const wall = level.wall.slice();
    for (const other of rooms) {
      if (other === room) continue;
      for (const b of other.done ? other.goals : other.boxes) wall[b] = 1;
    }
    const sub = {
      w: level.w,
      h: level.h,
      wall,
      goals: room.goals.slice().sort((a, b) => a - b),
      boxes: room.boxes.slice().sort((a, b) => a - b),
      player,
    };
    const solvedRoom = solvePushOptimal(sub, MAX_STATES, true);
    if (solvedRoom === null) return null;
    pushes += solvedRoom.pushes;
    moves += solvedRoom.moves;
    player = endOf(level.w, player, solvedRoom.moves);
    room.done = true;
  }
  return { pushes, moves };
}

/** Solve one level's text; '' when no optimal solution was found. */
function solve(text) {
  const level = parseLevel(text);
  if (level.boxes.every((b) => level.goals.includes(b))) return '';
  const byRooms = solveByRooms(level);
  if (byRooms !== null) return byRooms.moves;
  const whole = solvePushOptimal(level, MAX_STATES_WHOLE, false);
  return whole === null ? '' : whole.moves;
}

for (const id of readdirSync(I).sort()) {
  const moves = solve(readFileSync(join(I, id, 'level.txt'), 'utf8'));
  mkdirSync(join(O, id), { recursive: true });
  writeFileSync(join(O, id, 'solution.txt'), `${moves}\n`);
}
